package com.team7.rental.notification.entity;

/**
 * 알림 종류 (docs/state-machines.md §5 NotificationType). 이름은 문서 코드와 정확히 같다.
 * KEYWORD_MATCHED·APPOINTMENT_REMINDER는 3순위라 아직 발행하지 않고, REVIEW_RECEIVED는 후기(REQ-034) 구현 때 발행한다.
 */
public enum NotificationType {
	RESERVATION_CONFIRMED,
	PAYMENT_COMPLETED,
	RESERVATION_CANCELED,
	CANCEL_AGREEMENT_REQUESTED,
	CANCEL_AGREEMENT_RESULT,
	HANDOVER_CONFIRMED,
	HANDOVER_REMINDER,
	RETURN_REMINDER,
	RETURN_REQUESTED,
	LOST_REPORTED,
	INSPECTION_RESULT,
	DEPOSIT_REFUNDED,
	DEPOSIT_HELD,
	DEDUCTION_PROPOSED,
	DEDUCTION_ACCEPTED,
	DEDUCTION_REJECTED,
	OVERDUE,
	RENTAL_EXTENDED,
	REVIEW_RECEIVED,
	AI_COMPARE_DONE,
	/** 3순위 (REQ-052) */
	KEYWORD_MATCHED,
	/** 3순위 */
	APPOINTMENT_REMINDER
}
